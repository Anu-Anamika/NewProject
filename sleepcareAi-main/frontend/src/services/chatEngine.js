// Engine
// ---------------------------------------------------------------------------

let responseCounters = {};

/**
 * Returns a deterministic-cycling response from a list
 * so the bot doesn't always say the same thing.
 */
function pickResponse(key, responses) {
  if (!responseCounters[key]) responseCounters[key] = 0;
  const idx = responseCounters[key] % responses.length;
  responseCounters[key]++;
  return responses[idx];
}

/**
 * Main function: takes user input string, returns bot reply string.
 * @param {string} input
 * @returns {string}
 */
export function getBotReply(input) {
  const text = input.trim().toLowerCase();

  if (!text) return "Please type a question — I'd love to help! 😊";

  for (const rule of RULES) {
    for (const pattern of rule.patterns) {
      if (pattern.test(text)) {
        // Use rule index as stable key for cycling
        const key = RULES.indexOf(rule);
        return pickResponse(key, rule.responses);
      }
    }
  }

  return pickResponse('fallback', FALLBACKS);
}

