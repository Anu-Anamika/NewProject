/**
 * Normalizes input condition string or prediction object to standard key:
 * 'insomnia' | 'sleep_apnea' | 'no_disorder'
 *
 * @param {string|Object} condition
 * @returns {'insomnia' | 'sleep_apnea' | 'no_disorder'}
 */
export function normalizeCondition(condition) {
  if (!condition) return 'no_disorder';

  let raw = condition;
  if (typeof condition === 'object') {
    raw =
      condition.sleep_disorder ||
      condition.predicted_disorder ||
      condition.label ||
      condition.condition ||
      '';
  }

  const str = String(raw).trim().toLowerCase();

  if (str.includes('insomnia')) {
    return 'insomnia';
  }

  if (
    str.includes('apnea') ||
    str.includes('osa') ||
    str.includes('obstructive')
  ) {
    return 'sleep_apnea';
  }

  if (
    str.includes('none') ||
    str.includes('no sleep') ||
    str.includes('healthy') ||
    str.includes('no_disorder') ||
    str.includes('normal')
  ) {
    return 'no_disorder';
  }

  return 'no_disorder';
}

